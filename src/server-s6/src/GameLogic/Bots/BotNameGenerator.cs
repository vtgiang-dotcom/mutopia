    private readonly IRandomizer _randomizer = Rand.GetRandomizer();

    /// <summary>
    /// Generates a name which is not yet used, neither within this run nor in the database.
    /// </summary>
    /// <param name="context">The context used to check name availability.</param>
    /// <param name="reserved">The set of names already handed out in this run; the returned name is added to it.</param>
    /// <param name="cancellationToken">The cancellation token.</param>
    /// <returns>A unique, valid character name.</returns>
    public async ValueTask<string> GenerateUniqueAsync(IPlayerContext context, ISet<string> reserved, CancellationToken cancellationToken = default)
    {
        // The curated pool (~700 names) is smaller than a full population (360 accounts x 5 characters =
        // 1800 characters), and MU names must be globally unique. Once the plain name is taken - in this
        // run or in the database - fall back to a numeric-suffixed variant (the way a real player
        // disambiguates a taken name), so generation never deadlocks on name exhaustion.
        for (var attempt = 0; attempt < 500; attempt++)
        {
            var baseName = Names.SelectRandom(this._randomizer)!;
            for (var variant = 0; variant < 100; variant++)
            {
                var name = variant == 0 ? baseName : WithSuffix(baseName, variant);
                if (!reserved.Add(name))
                {
                    continue;
                }

                var existing = await context.GetAccountByCharacterNameAsync(name, cancellationToken).ConfigureAwait(false);
                if (existing is null)
                {
                    return name;
                }
            }
        }

        throw new InvalidOperationException("Could not generate a unique bot character name after many attempts.");
    }

    /// <summary>
    /// Appends a numeric suffix to a base name, trimming the base so the result stays within the
    /// 10-character MU name limit (e.g. "Aragorn" + "42" -> "Aragorn42"; a 10-character base is cut to 8).
    /// </summary>
    /// <param name="baseName">The curated base name.</param>
    /// <param name="suffix">The numeric suffix.</param>
    /// <returns>The suffixed, limit-compliant name.</returns>
    private static string WithSuffix(string baseName, int suffix)
    {
        var suffixText = suffix.ToString();
        var maxBase = 10 - suffixText.Length;
        return baseName.Length <= maxBase ? baseName + suffixText : baseName[..maxBase] + suffixText;
    }
